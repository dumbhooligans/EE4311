%[text] %[text:anchor:H_METHOD1] ### 2.5    Method 1: Rule Weighting
%[text] **Tuning technique used in this file: Rule Weighting.**
%[text]
%[text] The 5×5 rule base (Section 3.3) is left with its original antecedents/consequents
%[text] from the baseline model. Instead of moving membership-function breakpoints or
%[text] crisp output levels, each of the 25 rules is given its own weight
%[text] `w_ij in (0, 1]`, stored in `params.RULE_W(i,j)` (`i` = p-term, `j` = d-term, both
%[text] ordered NB,NS,ZO,PS,PB). The weight is passed to `addRule()` as the trailing
%[text] `(weight)` term and scales that rule's contribution to the `wtaver`
%[text] weighted-average defuzzification:
%[text]
%[text] $$f = \frac{\sum_{i,j} w_{ij}\, \min(\mu_p^i,\mu_d^j)\, z_{ij}}{\sum_{i,j} w_{ij}\, \min(\mu_p^i,\mu_d^j)}$$
%[text]
%[text] **Why this can fix the baseline's problem.** At the exact origin (p=0, d=0) only
%[text] the single rule `p==ZO & d==ZO => f==ZO` fires (its neighbours are 0 there because
%[text] the ZO terms are triangular, not flat-topped), so the controller is forced to output
%[text] exactly 0 N whenever gamma settles to exactly 0 deg. Since gravity along the
%[text] 30-degree slope (`constants.WEIGHT`) is nonzero, 0 N can never hold the pendulum
%[text] at gamma=0 deg — the baseline model consequently settles at a large, constant
%[text] offset (~1.8-2.0 deg) instead of 0 deg, for every starting angle. Away from the
%[text] exact origin, however, two adjacent terms overlap in each input, so 2-4 rules
%[text] fire simultaneously; rule weighting lets us bias *which* of those overlapping
%[text] rules dominates the blend, shifting the true equilibrium point much closer to
%[text] gamma=0 deg and shaping how fast/aggressively the response gets there.
%[text]
%[text] **Method.** `params.RULE_W` was tuned numerically (offline, in a companion script,
%[text] not part of this worksheet) by minimizing a smooth cost combining (a) the
%[text] integral-squared angle error over the whole 5 s run, weighted more heavily for
%[text] t > 0.5 s, (b) explicit penalties on final steady-state error and overshoot, and
%[text] (c) penalties on force chattering (sum of squared force jumps) and on residual
%[text] angular-velocity oscillation in the second half of the run -- an early version
%[text] without (c) minimized settling time/overshoot/steady-state error well but drove
%[text] several rule weights to their 0.02 floor, which made the controller bang-bang
%[text] between rules and produced persistent ~5 deg/s velocity chatter that violated the
%[text] "negligible oscillations" requirement even though gamma itself looked converged.
%[text] Adding the chattering penalty traded a little steady-state accuracy for a
%[text] genuinely smooth, non-oscillatory response. Optimized with MATLAB's `fminsearch`
%[text] from several random restarts, across all four `constants.START_GAMMAS`
%[text] simultaneously. \
params.RULE_W = [ ...
    1.0000, 1.0000, 0.0200, 0.0200, 0.0200; ... % p=NB
    0.0200, 0.2644, 0.0200, 0.0329, 0.1071; ... % p=NS
    1.0000, 0.2884, 0.1765, 0.4380, 1.0000; ... % p=ZO
    1.0000, 0.2612, 1.0000, 1.0000, 0.1292; ... % p=PS
    0.6889, 1.0000, 0.0200, 0.0454, 1.0000  ... % p=PB
    ]; % rows: p={NB,NS,ZO,PS,PB}, cols: d={NB,NS,ZO,PS,PB}

