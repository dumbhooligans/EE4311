%[text] ## 4    Controller
function f = controller(fis, gamma, gamma_vel)
p = 0 - gamma; % (1) proportional error, desired angle - current angle
d = 0 - gamma_vel; % (2) derivative error, desired velocity - current velocity
f = evalfis(fis, [p, d]); % (3) crisp force from the Sugeno FIS

end
