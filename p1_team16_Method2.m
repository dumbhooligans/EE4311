%[text] %[text:anchor:H_METHOD2] ### 2.5    Method D: ZO Dead-Zone Width
%[text] **Tuning technique used in this file: ZO dead-zone width.**
%[text]
%[text] The baseline input membership functions place the ZO/NS boundary (and
%[text] ZO/PS boundary) at `+/-2.6 deg` for the proportional error and
%[text] `+/-35 deg/s` for the derivative error -- i.e. the ZO term's half-width.
%[text] This file keeps every other lever fixed at baseline (crisp output values
%[text] in Section 2.4, all 25 rules and rule weights, inference methods) and
%[text] tunes only that half-width, symmetrically, for each input:
%[text] `params.ZP` for the proportional-error ZO half-width and `params.ZD` for
%[text] the derivative-error ZO half-width. The NS/PB and NB/PS breakpoints that
%[text] touch the ZO term move together with it, so the five terms per input
%[text] still exactly tile the universe (no gaps, no added overlap).
%[text]
%[text] **Why this can help.** At `p=d=0` only the
%[text] `p==ZO & d==ZO => f==ZO` rule fires, forcing `f=0` -- the same root cause
%[text] diagnosed for the baseline in Method C. Narrowing the ZO region shrinks
%[text] the area over which the controller is confined to this single,
%[text] zero-output rule: a smaller angle error is enough to bring a
%[text] non-zero-consequent rule (NS or PS) into play, so the controller starts
%[text] producing corrective/holding force sooner.
%[text]
%[text] **Method.** `params.ZP` and `params.ZD` were tuned by a 2D grid search,
%[text] then a continuous `fminsearch` refinement (offline, in a companion
%[text] script, not part of this worksheet) over a cost combining worst-case
%[text] settling time, overshoot, steady-state error, final-second force range,
%[text] and -- critically -- a *ringing* penalty (number of times `gamma_vel`
%[text] changes sign over the whole run, beyond the one expected reversal on
%[text] the way to the target) across all four `constants.START_GAMMAS`.
%[text]
%[text] **Revision note.** The first setting tried here (`ZP=0.5`, `ZD=22`)
%[text] minimised settling time and steady-state error well in isolation, but
%[text] visibly wobbled -- `gamma` rang several times before flattening out,
%[text] because narrowing the ZO region that far raises the effective
%[text] controller gain enough to overshoot, correct, overshoot again, several
%[text] times. The original search only scored the *final* second of each run,
%[text] the same blind spot Method C's first attempt had, just in the
%[text] transient instead of the tail, so it never penalised this. Adding the
%[text] ringing term and re-searching gives `ZP=1.10`, `ZD=23`: every response
%[text] now shows exactly one overshoot-and-correct, then settles cleanly, at
%[text] the cost of settling time landing at `0.50 s` (the target boundary)
%[text] rather than comfortably under it -- searching further (including a
%[text] continuous `fminsearch` refinement, not just a grid) could not push
%[text] settling time below `0.50 s` without reintroducing a second wobble, so
%[text] this appears to be a genuine limit of tuning `ZP`/`ZD` alone. \
params.ZP = 1.10;  % proportional-error ZO half-width, deg (baseline: 2.6)
params.ZD = 23;    % derivative-error ZO half-width, deg/s (baseline: 35)

params.P_NB = [-20, -20, -10, -params.ZP];
params.P_NS = [-10, -params.ZP, -params.ZP, 0];
params.P_ZO = [-params.ZP, 0, 0, params.ZP];
params.P_PS = [0, params.ZP, params.ZP, 10];
